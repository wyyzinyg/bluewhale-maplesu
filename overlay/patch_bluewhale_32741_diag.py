"""32741 diag UX: drop recheck, save-only report, no per-resume recheck.

User feedback 2026-11-28:
  1. 每次进 App 会自动检测，设置页 Root 诊断卡上的「重新检测」按钮多余 -> 删掉。
  2. 「复制诊断报告」-> 行为改为只保存到 Download，不再复制剪贴板、不再弹分享面板。
  3. 回到前台每 1 秒自动 recheck 造成日志刷屏（39 条/12 秒）-> 去掉 ON_RESUME 自动重探。

The target file is generated by the upstream DSH 32739 payload
(manager/src/main/java/com/maplesu/core/ui/screen/home/RootDiagnostics.kt),
so this patch is a text-level follow-up applied after that payload ran.
"""

from pathlib import Path

REL = "manager/src/main/java/com/maplesu/core/ui/screen/home/RootDiagnosticsUi.kt"

RECHECK_MIUIX = '''                MiuixTextButton(
                    text = stringResource(R.string.root_diagnostics_recheck),
                    onClick = onRecheck,
                    colors = MiuixButtonDefaults.textButtonColorsPrimary(),
                    modifier = Modifier.testTag("root_diagnostics_recheck"),
                )
'''

RECHECK_MATERIAL = '''                MaterialTextButton(
                    onClick = onRecheck,
                    modifier = Modifier.testTag("root_diagnostics_recheck"),
                ) { MaterialText(stringResource(R.string.root_diagnostics_recheck)) }
'''

OLD_RESUME = '''    LifecycleEventEffect(Lifecycle.Event.ON_RESUME) {
        // Requirement: one recheck after returning from background, debounced by 1s.
        // The scan runs on Dispatchers.IO; the cached hashes keep repeated resumes cheap.
        val now = SystemClock.elapsedRealtime()
        if (now - lastAutoCheck < 1_000L) return@LifecycleEventEffect
        lastAutoCheck = now
        scope.launch {
            delay(1_000)
            startCollect("resume", rerunRootCheck = true)
        }
    }
'''

OLD_DELIVER_START = "private fun deliverRootDiagnosticsReport(context: Context, snapshot: RootDiagnosticsSnapshot) {"

NEW_DELIVER = '''private fun deliverRootDiagnosticsReport(context: Context, snapshot: RootDiagnosticsSnapshot) {
    // 3.22.2-bw: 只落盘到 Download，不再复制剪贴板、不再拉起分享面板。
    val report = formatRootDiagnosticsReport(snapshot)
    Thread {
        val uri = saveRootDiagnosticsToDownloads(context, report)
        val message = if (uri == null) {
            context.getString(R.string.root_diagnostics_export_failed)
        } else {
            "诊断报告已保存到 Download/BluefishSU"
        }
        android.os.Handler(context.mainLooper).post {
            Toast.makeText(context, message, Toast.LENGTH_LONG).show()
        }
    }.start()
}
'''


def _drop_recheck_buttons(text: str):
    """Line-level removal: drop the TextButton block whose label is root_diagnostics_recheck."""
    lines = text.split("\n")
    out = []
    removed = 0
    i = 0
    while i < len(lines):
        stripped = lines[i].strip()
        if stripped in ("MiuixTextButton(", "MaterialTextButton("):
            label_hit = any("root_diagnostics_recheck" in lines[k] for k in range(i, min(i + 7, len(lines))))
            if label_hit:
                for j in range(i + 1, min(i + 9, len(lines))):
                    s = lines[j].strip()
                    if s == ")" or s.startswith(") {"):
                        i = j + 1
                        removed += 1
                        break
                else:
                    out.append(lines[i])
                    i += 1
                continue
        out.append(lines[i])
        i += 1
    return "\n".join(out), removed


def _rename_copy_labels(root: Path) -> None:
    targets = (
        ("manager/src/main/res/values-zh-rCN/root_diagnostics.xml", "复制诊断报告", "保存诊断报告"),
        ("manager/src/main/res/values/root_diagnostics.xml", "Copy report", "Save report"),
    )
    for rel, old_text, new_text in targets:
        path = root / rel
        if not path.is_file():
            print(f"skip: {rel} missing")
            continue
        text = path.read_text(encoding="utf-8")
        if old_text in text:
            text = text.replace(old_text, new_text, 1)
            path.write_text(text, encoding="utf-8")
            print(f"renamed label in {rel}: {old_text} -> {new_text}")
        else:
            print(f"skip: {rel} already renamed")


def patch_32741_diag(root: Path) -> None:
    _rename_copy_labels(root)
    path = root / REL
    if not path.is_file():
        print("skip: RootDiagnostics.kt missing (upstream payload not applied)")
        return
    text = path.read_text(encoding="utf-8")

    if "root_diagnostics_recheck" in text:
        text, removed = _drop_recheck_buttons(text)
        print(f"patched RootDiagnosticsUi.kt: recheck buttons removed ({removed})")
    else:
        print("skip: recheck button already removed")

    if OLD_RESUME in text:
        text = text.replace(OLD_RESUME, "", 1)
        print("patched RootDiagnostics.kt: per-resume recheck removed")
    else:
        print("skip: resume recheck block not found (already removed?)")

    idx = text.find(OLD_DELIVER_START)
    if idx < 0:
        print("skip: deliverRootDiagnosticsReport not found")
    else:
        end = text.find("\n@Composable", idx)
        if end < 0:
            raise SystemExit("FATAL: deliverRootDiagnosticsReport end marker not found")
        text = text[:idx] + NEW_DELIVER + text[end:]
        print("patched RootDiagnostics.kt: save-only report delivery")

    path.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    import sys

    patch_32741_diag(Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve())
