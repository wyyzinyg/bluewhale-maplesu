def bump_version() -> None:
    p = ROOT / GRADLE
    if not p.is_file():
        print("SKIP bump: missing %s" % GRADLE)
        return
    text = p.read_text(encoding="utf-8")
    pairs = (("versionCode = 32751", "versionCode = 32752"),
             ('versionName = "3.22.12-bw"', 'versionName = "3.22.13-bw"'))
    hit = 0
    for old, new in pairs:
        if new in text:
            continue
        if old not in text:
            print("WARN bump: '%s' not found (dry tree may be stale)" % old)
            continue
        text = text.replace(old, new, 1)
        hit += 1
    p.write_text(text, encoding="utf-8")
    if hit:
        print("bumped manager version -> 32752/3.22.13-bw")


