def swap(rel: str, pairs, tag: str) -> None:
    p = ROOT / rel
    if not p.is_file():
        print("SKIP 32752: missing %s" % rel)
        return
    text = p.read_text(encoding="utf-8")
    hit = 0
    for old, new in pairs:
        if new in text:
            print("SKIP 32752 %s: already applied (%s)" % (tag, old[:40]))
            continue
        if old not in text:
            print("WARN 32752 %s: anchor not found (%s)" % (tag, old[:40]))
            continue
        text = text.replace(old, new, 1)
        hit += 1
    if hit:
        p.write_text(text, encoding="utf-8")
        print("patched: %s (%d)" % (tag, hit))


def default_theme_identity() -> None:
    """默认主题从「MapleSU + indigo」改成「BluefishSU + bluewhale」。"""
    doc = ROOT / THEME_DOC
    repo = ROOT / THEME_REPO
    if not doc.is_file() or not repo.is_file():
        print("SKIP 32752: missing theme source")
        return
    t = doc.read_text(encoding="utf-8")
    pairs = [
        ('val name: String = "MapleSU"', 'val name: String = "BluefishSU"'),
        ('j.optString("meta_name", "MapleSU")', 'j.optString("meta_name", "BluefishSU")'),
        ('"indigo" to 0xFF4355B9, ', ('"bluewhale" to 0xFF2856D8, "indigo" to 0xFF4355B9, ')),
        ('"customColor" to "indigo"', '"customColor" to "bluewhale"'),
        ('colors.getValue("indigo")', 'colors.getValue("bluewhale")'),
    ]
    if '"bluewhale" to' in t:
        pairs = [x for x in pairs if x[0] != '"indigo" to 0xFF4355B9, ']
    hits = 0
    for old, new in pairs:
        if t.count(old) == 0:
            print("MISS  theme doc: %s" % old[:46])
        else:
            t = t.replace(old, new, 1)
            hits += 1
    doc.write_text(t, encoding="utf-8")
    r = repo.read_text(encoding="utf-8")
    if '.ifBlank { "MapleSU" }' in r:
        r = r.replace('.ifBlank { "MapleSU" }', '.ifBlank { "BluefishSU" }', 1)
        hits += 1
    if '/MapleSU/Themes' in r:
        r = r.replace('/MapleSU/Themes', '/BluefishSU/Themes', 1)
        hits += 1
    repo.write_text(r, encoding="utf-8")
    print("patched: default theme identity %d/7" % hits)


